#!/usr/bin/env node
/**
 * Publishes the validated realistic piece PNGs as static web assets and
 * generates the display mapping module.
 *
 * - runs inspectPieceAssets in strict mode (manifestVersion=2, ready, 24/24)
 * - deduplicates views that share one source path (symmetry)
 * - copies each original PNG byte-for-byte to src/web/public/pieces/staunton-v3/
 *   and re-checks the copied SHA-256 against the manifest
 * - writes src/web/piece-assets.generated.js with relative URLs only
 *
 * No image is generated, resized, recolored, mirrored or rotated.
 *
 * Usage: node scripts/prepare-piece-assets.js
 */
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, realpathSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inspectPieceAssets } from './check-piece-assets.js';

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC_ROOT = resolve(PROJECT_ROOT, 'src', 'web', 'public');
const PIECES_PARENT = resolve(PUBLIC_ROOT, 'pieces');
const PIECES_DIR = resolve(PIECES_PARENT, 'staunton-v3');
const GENERATED_MODULE = resolve(PROJECT_ROOT, 'src', 'web', 'piece-assets.generated.js');

const sha256File = (filePath) => createHash('sha256').update(readFileSync(filePath)).digest('hex');

function validateOwnOutputDir() {
  const resolved = resolve(PIECES_DIR);
  if (dirname(resolved) !== PIECES_PARENT || basename(resolved) !== 'staunton-v3') {
    throw new Error(`拒绝清理非本任务输出目录：${resolved}`);
  }
  if (!existsSync(PUBLIC_ROOT)) throw new Error(`缺少目录：${PUBLIC_ROOT}`);
  if (lstatSync(PUBLIC_ROOT).isSymbolicLink()) throw new Error('拒绝通过符号链接操作 public 目录');
  const realPublic = realpathSync(PUBLIC_ROOT);
  const realProject = realpathSync(PROJECT_ROOT);
  if (!realPublic.startsWith(realProject + sep)) throw new Error('public 目录真实路径越出项目');
  if (existsSync(PIECES_PARENT)) {
    if (lstatSync(PIECES_PARENT).isSymbolicLink()) throw new Error('拒绝通过符号链接写入 pieces 目录');
    const realParent = realpathSync(PIECES_PARENT);
    if (!realParent.startsWith(realPublic + sep)) throw new Error('pieces 目录真实路径越出 public');
  }
  if (existsSync(resolved)) {
    if (lstatSync(resolved).isSymbolicLink()) throw new Error('拒绝通过符号链接清理生成目录');
    const realPieces = realpathSync(resolved);
    if (!realPieces.startsWith(realPublic + sep)) throw new Error('生成目录真实路径越出 public');
  }
}

function cleanOwnOutputDir() {
  validateOwnOutputDir();
  const resolved = resolve(PIECES_DIR);
  if (existsSync(resolved)) rmSync(resolved, { recursive: true, force: true });
  mkdirSync(resolved, { recursive: true });
}

function outputsMatch(uniqueByPath, publicNameByPath) {
  validateOwnOutputDir();
  if (!existsSync(PIECES_DIR)) return false;
  const files = readdirSync(PIECES_DIR, { withFileTypes: true });
  if (files.length !== uniqueByPath.size || files.some((file) => !file.isFile())) return false;
  return [...uniqueByPath].every(([path, entry]) => {
    const destination = join(PIECES_DIR, publicNameByPath.get(path));
    return existsSync(destination) && sha256File(destination) === entry.meta.sha256;
  });
}

function buildGeneratedModule(manifest, publicNameByPath, report) {
  const data = {
    manifest: {
      path: 'assets/pieces-manifest.json',
      version: manifest.manifestVersion,
      status: manifest.status,
      style: manifest.style,
    },
    rendering: manifest.rendering,
    pieces: {},
  };
  for (const piece of manifest.pieces) {
    const views = {};
    for (const view of ['front', 'rear']) {
      const meta = piece.views[view];
      views[view] = {
        url: `./pieces/staunton-v3/${publicNameByPath.get(meta.path)}`,
        width: meta.width,
        height: meta.height,
        contentBounds: meta.contentBounds,
      };
    }
    data.pieces[piece.id] = {
      color: piece.color,
      type: piece.type,
      relativeHeight: piece.relativeHeight,
      views,
    };
  }
  const header = [
    '// Generated by scripts/prepare-piece-assets.js. Do not edit manually.',
    `// Source: assets/pieces-manifest.json (manifestVersion=${manifest.manifestVersion}, status=${manifest.status}); ${report.counts.provided}/${report.counts.total} views.`,
    '',
  ].join('\n');
  return `${header}export const PIECE_ASSETS = ${JSON.stringify(data, null, 2)};\n`;
}

function writeAtomically(filePath, content) {
  if (existsSync(filePath) && readFileSync(filePath, 'utf8') === content) return;
  const temp = `${filePath}.tmp-${process.pid}`;
  writeFileSync(temp, content, 'utf8');
  renameSync(temp, filePath);
}

async function main() {
  const report = await inspectPieceAssets({ allowPartial: false });
  if (!report.ok) {
    for (const error of report.errors) console.error(`[pieces] 错误：${error}`);
    throw new Error('素材未通过严格校验，未生成公共资源');
  }
  if (report.manifest.status !== 'ready') throw new Error('仅发布 status=ready 的完整素材清单');

  // Deduplicate by source path; both symmetric slots keep their own mapping.
  const uniqueByPath = new Map();
  for (const entry of report.provided) {
    if (!uniqueByPath.has(entry.path)) uniqueByPath.set(entry.path, entry);
  }
  const publicNameByPath = new Map();
  const usedNames = new Set();
  for (const [sourcePath, entry] of uniqueByPath) {
    const extension = extname(sourcePath);
    let name = basename(sourcePath);
    if (usedNames.has(name)) name = `${basename(sourcePath, extension)}-${entry.meta.sha256.slice(0, 8)}${extension}`;
    if (usedNames.has(name)) throw new Error(`公共资源名冲突：${name}`);
    usedNames.add(name);
    publicNameByPath.set(sourcePath, name);
  }

  const reuseCopies = outputsMatch(uniqueByPath, publicNameByPath);
  if (!reuseCopies) cleanOwnOutputDir();
  let copiedBytes = 0;
  for (const [sourcePath, entry] of uniqueByPath) {
    const destination = join(PIECES_DIR, publicNameByPath.get(sourcePath));
    if (!reuseCopies) copyFileSync(entry.absolute, destination);
    const copiedSha256 = sha256File(destination);
    if (copiedSha256 !== entry.meta.sha256) {
      throw new Error(`副本 SHA-256 与清单不一致：${publicNameByPath.get(sourcePath)}`);
    }
    copiedBytes += statSync(destination).size;
  }

  const moduleContent = buildGeneratedModule(report.manifest, publicNameByPath, report);
  writeAtomically(GENERATED_MODULE, moduleContent);

  const uniqueCount = uniqueByPath.size;
  console.log(`[pieces] 已发布 ${uniqueCount} 张原图（${report.counts.provided} 个视图槽）到 src/web/public/pieces/staunton-v3/，共 ${copiedBytes} 字节`);
  console.log(`[pieces] 已生成 src/web/piece-assets.generated.js（${report.manifest.pieces.length} 个 piece）`);
}

main().catch((error) => {
  console.error(`[pieces] 错误：${error.message}`);
  process.exitCode = 1;
});
